// Default: lossless copies of the best local sources. --light is an explicit opt-in.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
let sharp;
try{sharp=require('sharp');}catch(error){sharp=require(process.env.SHARP_MODULE||'/Applications/ChatGPT.app/Contents/Resources/cua_node/lib/node_modules/sharp');}
process.chdir(path.resolve(__dirname,'..'));
const previous=fs.existsSync('utils/asset-runtime.js')?require('../utils/asset-runtime'):null;
const sources=previous?Object.keys(previous).map(file=>file.slice(1)):JSON.parse(fs.readFileSync('output/upload-audit.json')).retainedFiles.filter(file=>/^assets\//.test(file)&&!file.startsWith('assets/previews/')&&/\.(png|jpg)$/.test(file));
const light=process.argv.includes('--light');
(async()=>{
 const mapping={},rows=[];let total=0;
 for(const source of sources){
  const backup='output/upload-originals/'+source.slice('assets/'.length);
  const input=!light&&fs.existsSync(backup)?backup:source;
  const target=!light&&source.endsWith('.png')?source:'assets/'+(light?'optimized/':'highres/')+source.slice('assets/'.length);fs.mkdirSync(path.dirname(target),{recursive:true});
  const original=fs.readFileSync(input),meta=await sharp(original).metadata();let encoded;
  if(!light){encoded=original;}
  else if(source.endsWith('.png')){
   encoded=await sharp(original).png({palette:true,colours:64,quality:80,effort:10,compressionLevel:9,dither:0}).toBuffer();
   if(encoded.length>original.length)encoded=original;
  }else{
   const panorama=source.startsWith('assets/panoramas/');
   encoded=await sharp(original).resize({width:panorama?1024:288,withoutEnlargement:true}).jpeg({quality:panorama?40:45,mozjpeg:true,chromaSubsampling:'4:2:0'}).toBuffer();
  }
  if(target!==source)fs.writeFileSync(target,encoded);mapping['/'+source]='/'+target;total+=encoded.length;
  const result=await sharp(encoded).metadata();
  if(source.startsWith('assets/panoramas/'))assert.equal(result.width,result.height*2,'Panorama must retain 2:1 projection');
  if(meta.hasAlpha)assert(result.hasAlpha,'Lost transparency: '+source);
  rows.push({source,input,target,originalBytes:original.length,bytes:encoded.length,width:result.width,height:result.height});
 }
 if(light)assert(total<200000,'Offline media must fit below 200000 bytes: '+total);
 const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]);
 // Static WXML images must follow the same quality profile as JS-bound images.
 for(const file of [...walk('pages'),...walk('components')].filter(f=>f.endsWith('.wxml'))){
  const text=fs.readFileSync(file,'utf8');
  fs.writeFileSync(file,text.replace(/\/assets\/(?:optimized\/|highres\/)?[A-Za-z0-9_./-]+\.(?:png|jpe?g)/g,value=>{const source=value.replace(/^\/assets\/(?:optimized|highres)\//,'/assets/');return mapping[source]||source;}));
 }
 const fallbackFile='utils/asset-fallbacks.js';
 fs.writeFileSync(fallbackFile,fs.readFileSync(fallbackFile,'utf8').replace(/\/assets\/(?:optimized|highres)\//g,'/assets/'+(light?'optimized/':'highres/')));
 fs.writeFileSync('utils/asset-runtime.js','// Generated by scripts/optimize-runtime-assets.cjs; original files stay on disk.\nmodule.exports='+JSON.stringify(mapping,null,2)+';\n');
 fs.mkdirSync('output',{recursive:true});fs.writeFileSync('output/runtime-media.json',JSON.stringify({profile:light?'light':'original-quality',totalBytes:total,files:rows},null,2)+'\n');
 console.log('Generated '+rows.length+' offline images ('+(light?'light':'original quality')+'): '+total+' bytes.');
})().catch(error=>{console.error(error);process.exitCode=1;});
