// Writes utils/guide-config.local.js from api-config/.env.local.
// Usage (from work/):
//   node scripts/configure-guide.cjs                      use GUIDE_MODE from the env file
//   node scripts/configure-guide.cjs --mode demo          offline demo, no credential in the package
//   node scripts/configure-guide.cjs --mode live-direct   DEVELOPMENT ONLY: embeds the key in the package
//   node scripts/configure-guide.cjs --mode live-relay --relay-url https://your.domain/guide
// Options: --env <file>  --no-stream
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const arg = name => { const i = process.argv.indexOf('--' + name); return i < 0 ? undefined : process.argv[i + 1]; };
const envFile = path.resolve(arg('env') || require('./lib/project-paths.cjs').env);
const env = {};
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Z_]+)=(.*)$/.exec(line.trim());
    if (m) env[m[1]] = m[2].replace(/^"|"$/g, '');
  }
}
const aliases = { live: 'live-direct', direct: 'live-direct', relay: 'live-relay' };
let mode = arg('mode') || env.GUIDE_MODE || 'demo';
mode = aliases[mode] || mode;
if (!['demo', 'live-direct', 'live-relay'].includes(mode)) throw new Error('Unknown mode: ' + mode);
const config = { mode };
if (mode !== 'demo') {
  config.provider = 'CherryIN';
  if (process.argv.includes('--no-stream')) config.stream = false;
}
if (mode === 'live-direct') {
  if (!env.CHERRYIN_API_KEY) throw new Error('CHERRYIN_API_KEY is missing in ' + envFile);
  config.baseUrl = env.CHERRYIN_BASE_URL || 'https://open.cherryin.net/v1';
  config.model = env.CHERRYIN_MODEL || 'agent/qwen3-coder-30b-a3b-instruct(free)';
  config.apiKey = env.CHERRYIN_API_KEY;
}
if (mode === 'live-relay') {
  config.relayUrl = arg('relay-url') || env.GUIDE_RELAY_URL;
  if (!/^https:\/\//.test(config.relayUrl || '')) throw new Error('live-relay needs --relay-url https://... (mini-programs only allow HTTPS request domains)');
}
const header = [
  '// Local guide configuration. Generated by scripts/configure-guide.cjs.',
  mode === 'live-direct'
    ? '// DEVELOPMENT ONLY: this file embeds an API key. Never upload or publish a build that contains it.\n// Run "node scripts/configure-guide.cjs --mode live-relay --relay-url https://..." or "--mode demo" before uploading.'
    : '// No credential is stored in this file.'
].join('\n');
fs.writeFileSync(path.join(root, 'utils', 'guide-config.local.js'), header + '\nmodule.exports = ' + JSON.stringify(config, null, 2) + ';\n');
const shown = Object.assign({}, config);
if (shown.apiKey) shown.apiKey = '<redacted, ' + config.apiKey.length + ' characters>';
console.log('Wrote utils/guide-config.local.js:', JSON.stringify(shown));
if (mode === 'live-direct') console.log('Reminder: add ' + new URL(config.baseUrl).origin + ' to the mini-program request domain list. This build must not be uploaded.');
